#!/bin/bash
# Oracle OPS Installer library: the Oracle OPS repository database for Fresh Installation (0.3.0)
# Sourced only by the integrity loader in oracle-ops-installer.sh (digest-verified). Function definitions and constant
# global assignments only: nothing here may run a command at load time.
#
#   1. The DBA SQL (dba_schema_sql): tablespace OPS_DATA (if missing), users OPS_OWNER and OPS_RUNTIME, their privileges, and
#      SELECT on the DBA_* views the Oracle OPS scripts check (DB_DICTIONARY_VIEWS). Fixed names. It holds no password: SQL*Plus
#      asks the DBA for both (hidden). It creates no Oracle OPS table or package.
#   2. The installer then logs in AS OPS_OWNER (password typed hidden, kept only for this step, on the tool's standard input)
#      and runs the pinned release's own scripts unchanged, in the order of OPS_DB_SCRIPTS (oracle-ops-installer.sh; each file's
#      SHA-256 is checked first), plus the one grant the release has no script for (EXECUTE on OPS_RUN_API to OPS_RUNTIME,
#      required by V5_001 and by the service). An EMPTY schema gets everything; a COMPLETE one is left as it is; anything
#      in between stops the run - the installer never drops or replaces an object.

DB_JAVA=""          # the private JDK's java the database tool runs on
# DB_RUN_FILES (array, set by prepare_db_tool): the files the deploy runs, in order (names inside RUN_DIR/db)
DBA_SQL_FILE=""     # where the DBA SQL was written

# ---------------------------------------------------------------------------------------------------------------------------
# 1. The DBA SQL
# ---------------------------------------------------------------------------------------------------------------------------

dba_schema_sql() {
  local v
  cat <<EOF
-- =====================================================================================================================
-- Oracle OPS $OPS_VERSION - database prerequisites (generated by the Oracle OPS Installer $INSTALLER_VERSION)
--
-- Run ONCE, as a DBA (for example SYSTEM), in SQL*Plus or SQLcl, connected to the PDB (or non-CDB database) that will
-- hold the Oracle OPS repository - NOT to CDB\$ROOT. For example:
--     sqlplus system@//<db-host>:<port>/<service> @oracle-ops-schema.sql
--
-- Creates only: tablespace $DB_TABLESPACE (if it does not exist), users $DB_OWNER and $DB_RUNTIME, their privileges,
-- and SELECT on the DBA_* views that the Oracle OPS installation scripts check. The Oracle OPS tables and packages are
-- created afterwards by the installer, connected as $DB_OWNER.
-- The two passwords are asked below (input hidden) and are not stored in this file. Do not use " or ' in them.
-- After the installation the DBA may revoke the SELECT grants on the DBA_* views; a later upgrade needs them again.
-- =====================================================================================================================
whenever sqlerror exit failure rollback
whenever oserror exit failure rollback
set echo off
set verify off
set feedback on
set serveroutput on
prompt Oracle OPS database prerequisites
accept ops_datafile char default 'OMF' prompt 'Datafile for tablespace $DB_TABLESPACE (full path, or Enter for Oracle Managed Files): '
accept ops_owner_pw char prompt 'Password for the new user $DB_OWNER: ' hide
accept ops_runtime_pw char prompt 'Password for the new user $DB_RUNTIME: ' hide

declare
  l_count pls_integer;
begin
  if sys_context('USERENV', 'CON_NAME') = 'CDB\$ROOT' then
    raise_application_error(-20001, 'connected to CDB\$ROOT: connect to the PDB that will hold the Oracle OPS repository');
  end if;
  select count(*) into l_count from dba_users where username in ('$DB_OWNER', '$DB_RUNTIME');
  if l_count > 0 then
    raise_application_error(-20002, '$DB_OWNER or $DB_RUNTIME already exists: this script is for a new installation only');
  end if;
  select count(*) into l_count from dba_tablespaces where tablespace_name = '$DB_TABLESPACE';
  if l_count = 0 then
    if '&ops_datafile' = 'OMF' then
      execute immediate 'create tablespace ${DB_TABLESPACE,,} datafile size 512m autoextend on next 128m maxsize 8g';
    else
      execute immediate 'create tablespace ${DB_TABLESPACE,,} datafile ''&ops_datafile'' size 512m autoextend on next 128m maxsize 8g';
    end if;
    dbms_output.put_line('Tablespace $DB_TABLESPACE created.');
  else
    dbms_output.put_line('Tablespace $DB_TABLESPACE already exists and is used as it is.');
  end if;
end;
/

create user ${DB_OWNER,,} identified by "&ops_owner_pw" default tablespace ${DB_TABLESPACE,,} quota unlimited on ${DB_TABLESPACE,,};
create user ${DB_RUNTIME,,} identified by "&ops_runtime_pw" default tablespace ${DB_TABLESPACE,,};
undefine ops_owner_pw
undefine ops_runtime_pw

-- $DB_OWNER owns the Oracle OPS objects; privileges granted directly (the packages are definer's rights).
grant create session, create table, create sequence, create procedure to ${DB_OWNER,,};
-- $DB_RUNTIME is the Oracle OPS service's login: CREATE SESSION only (the installer grants EXECUTE on the two packages).
grant create session to ${DB_RUNTIME,,};
-- Read access for the checks inside the Oracle OPS installation scripts (run by the installer as $DB_OWNER).
EOF
  for v in $DB_DICTIONARY_VIEWS; do printf 'grant select on sys.%s to %s;\n' "${v,,}" "${DB_OWNER,,}"; done
  cat <<EOF

prompt Oracle OPS database prerequisites created: $DB_TABLESPACE, $DB_OWNER, $DB_RUNTIME.
prompt Give the two passwords to the Oracle OPS installer operator through your approved channel.
EOF
}

# ask_dba_sql_path: where to write the DBA SQL (default: root's home), validated; sets DBA_SQL_FILE.
ask_dba_sql_path() {
  local p def="$ROOT_HOME/oracle-ops-schema-$OPS_VERSION.sql" attempt
  for attempt in 1 2 3; do
    printf '      Save the DBA SQL to [%s]: ' "$def"
    read_line p || { echo; finish 5 "no file name was entered"; }
    p="${p:-$def}"
    if [[ ! "$p" =~ ^/[A-Za-z0-9._/-]+\.sql$ ]] || [[ "$p" == */../* ]]; then say "      Use an absolute path ending in .sql (letters, digits, '.', '_', '-', '/')."; continue; fi
    if [ -L "$p" ] || { [ -e "$p" ] && [ ! -f "$p" ]; }; then say "      $p is a link or not a regular file."; continue; fi
    if [ ! -d "$(dirname "$p")" ] || [ -L "$(dirname "$p")" ]; then say "      The directory $(dirname "$p") does not exist."; continue; fi
    if [ -e "$p" ] && ! confirm_yes "$p exists. Replace it?"; then continue; fi
    DBA_SQL_FILE="$p"; return 0
  done
  finish 2 "no usable file name after three attempts"
}

write_dba_sql() {
  local tmp
  tmp="$(mktemp "$(dirname "$1")/.oracle-ops-schema.XXXXXX")" || return 1
  if dba_schema_sql > "$tmp" && chmod 0644 -- "$tmp" && mv -f -T -- "$tmp" "$1"; then return 0; fi
  rm -f -- "$tmp"; return 1
}

# The stage: either the DBA has prepared the schema already, or the SQL is produced and the run waits for the DBA.
db_schema_stage() {
  local c
  say "      Oracle OPS needs, in the database: tablespace $DB_TABLESPACE, users $DB_OWNER (owns the Oracle OPS objects)"
  say "      and $DB_RUNTIME (the service's login). A DBA creates them; the installer then creates the tables and packages."
  say "        1) The DBA has not created them yet: give me the SQL for the DBA"
  say "        2) The DBA has already created them"
  choose c "      Choose 1 or 2: " 1 2
  [ "$c" = 1 ] || { log "DBA prerequisites: reported as already created"; return 0; }
  ask_dba_sql_path
  write_dba_sql "$DBA_SQL_FILE" || finish 1 "could not write $DBA_SQL_FILE"
  log "DBA SQL written: $DBA_SQL_FILE"
  echo
  say "      ------------------------------- $DBA_SQL_FILE -------------------------------"
  dba_schema_sql | sed 's/^/      | /'
  say "      ------------------------------------------------------------------------------------------"
  echo
  say "      Give this file to the DBA. The DBA runs it in the target PDB, for example:"
  say "        sqlplus system@//$DB_HOST:$DB_PORT/$DB_SERVICE @$(basename "$DBA_SQL_FILE")"
  say "      and gives you the two passwords. Nothing has been changed on this host yet."
  confirm_yes "Has the DBA run it successfully?" \
    || finish 5 "the installation waits for the DBA. Run the installer again when $DBA_SQL_FILE has been run (choose 2 at this step)"
}

# ---------------------------------------------------------------------------------------------------------------------------
# 2. The database tool
# ---------------------------------------------------------------------------------------------------------------------------

# private_java_path <home>: the pinned private JDK's java under <home>, if it is a root-owned regular executable (root never
# runs a program another account could have replaced). Prints the path; false otherwise.
private_java_path() {
  local v j
  v="$(sed -n 's/^jdk\.version=//p' "$OPS_SRC/deploy/java-runtime.properties" 2>/dev/null | head -n 1)" || v=""
  [[ "$v" =~ ^[0-9][0-9A-Za-z._+-]*$ ]] || return 1
  j="$1/runtime/java/$v/bin/java"
  [ -f "$j" ] && [ ! -L "$j" ] && [ -x "$j" ] && [ "$(stat -c %u -- "$j")" = "$ADMIN_UID" ] || return 1
  printf '%s' "$j"
}

# prepare_db_tool: RUN_DIR/db with the tool source, the release's JDBC driver and the verified scripts, in run order.
prepare_db_tool() {
  local d="$RUN_DIR/db" want jar_rel item sum kind rel name
  mkdir -m 0700 -- "$d" || finish 1 "cannot create $d"
  db_tool_source > "$d/$DB_TOOL_CLASS.java" || finish 1 "cannot write the database tool"
  want="$(sed -n 's/^OJDBC8_SHA256="\([0-9a-f]\{64\}\)"$/\1/p' "$OPS_SRC/service/build.sh" 2>/dev/null | head -n 1)" || want=""
  jar_rel="$(sed -n 's/^OJDBC8_JAR="\(vendor\/ojdbc8-[0-9.]*\.jar\)"$/\1/p' "$OPS_SRC/service/build.sh" 2>/dev/null | head -n 1)" || jar_rel=""
  [ -n "$want" ] && [ -n "$jar_rel" ] || finish 4 "the release does not name its JDBC driver (service/build.sh)"
  [ -f "$OPS_SRC/service/$jar_rel" ] && [ ! -L "$OPS_SRC/service/$jar_rel" ] || finish 4 "the release lacks its JDBC driver $jar_rel"
  [ "$(sha256sum -- "$OPS_SRC/service/$jar_rel" | cut -d' ' -f1)" = "$want" ] || finish 4 "the JDBC driver does not match the SHA-256 the release pins"
  cp -- "$OPS_SRC/service/$jar_rel" "$d/ojdbc8.jar" || finish 1 "cannot copy the JDBC driver"
  DB_RUN_FILES=()
  for item in "${OPS_DB_SCRIPTS[@]}"; do
    read -r sum kind rel <<< "$item"
    case "$kind" in
      grant)
        name="installer_grant_${rel}.sql"
        printf 'grant execute on %s.%s to %s;\n' "${DB_OWNER,,}" "$rel" "${DB_RUNTIME,,}" > "$d/$name" || finish 1 "cannot write $name"
        DB_RUN_FILES+=("$name") ;;
      run|include)
        [ -f "$OPS_SRC/$rel" ] && [ ! -L "$OPS_SRC/$rel" ] || finish 4 "the release lacks $rel (installer and release do not match)"
        [ "$(sha256sum -- "$OPS_SRC/$rel" | cut -d' ' -f1)" = "$sum" ] || finish 4 "$rel does not match the SHA-256 recorded in the installer"
        name="$(basename "$rel")"
        cp -- "$OPS_SRC/$rel" "$d/$name" || finish 1 "cannot copy $rel"
        [ "$kind" != run ] || DB_RUN_FILES+=("$name") ;;
      *) finish 1 "internal error: unknown database script kind $kind" ;;
    esac
  done
  log "database tool prepared: $d (${#DB_RUN_FILES[@]} scripts: ${DB_RUN_FILES[*]})"
}

DB_TOOL_RC=0
DB_TOOL_OUT=""
# run_db_tool <check|deploy>: runs the tool with the OPS_OWNER password on its standard input; output in DB_TOOL_OUT (a file in
# the root-only run directory) and, sanitised, in the log. Sets DB_TOOL_RC and DB_STATE.
run_db_tool() {
  local mode="$1" url views
  url="jdbc:oracle:thin:@//$DB_HOST:$DB_PORT/$DB_SERVICE"
  views="$(printf '%s' "$DB_DICTIONARY_VIEWS" | tr ' ' ',')"
  DB_TOOL_OUT="$RUN_DIR/db/tool-$mode.out"
  DB_TOOL_RC=0
  log "run: database tool $mode as $DB_OWNER at $url"
  if [ "$mode" = deploy ]; then
    printf '%s\n' "$OWNER_PW" | db_tool_exec "$DB_JAVA" deploy "$url" "$views" "${DB_RUN_FILES[@]}" > "$DB_TOOL_OUT" 2>&1 || DB_TOOL_RC=$?
  else
    printf '%s\n' "$OWNER_PW" | db_tool_exec "$DB_JAVA" check "$url" "$views" > "$DB_TOOL_OUT" 2>&1 || DB_TOOL_RC=$?
  fi
  sanitize_stream < "$DB_TOOL_OUT" | sed 's/^/    | /' >> "$LOG_FILE" || true
  log "exit status $DB_TOOL_RC: database tool $mode"
  DB_STATE="$(sed -n 's/^STATE \([A-Z]*\).*/\1/p' "$DB_TOOL_OUT" | tail -n 1)"
}

# show_db_results: the tool's checks and errors for the operator (sanitised).
show_db_results() {
  sed -n -e 's/^RESULT \([a-z-]*\) PASS \(.*\)/      [PASS] \1: \2/p' -e 's/^RESULT \([a-z-]*\) FAIL \(.*\)/      [FAIL] \1: \2/p' \
    -e 's/^STATE \(.*\)/      State: \1/p' -e 's/^ERROR \(.*\)/      ERROR: \1/p' "$DB_TOOL_OUT" | sanitize_stream
}

ask_owner_password() {
  say "      The installer logs in as $DB_OWNER to create the Oracle OPS tables and packages. The password is used only for"
  say "      this step: it is not shown, not stored and not written to the log."
  printf '      %s password: ' "$DB_OWNER"
  read_secret_line OWNER_PW || finish 5 "no password was entered"
  [ -n "$OWNER_PW" ] || finish 5 "no password was entered"
  [[ "$OWNER_PW" =~ ^[[:print:]]+$ ]] || { OWNER_PW=""; finish 2 "the password contains characters that cannot be used"; }
}

db_objects_stage() {
  local java attempt
  java="$(private_java_path "$TARGET_HOME")" || finish 1 "the private Java runtime is not usable under $TARGET_HOME/runtime/java"
  DB_JAVA="$java"
  prepare_db_tool
  for attempt in 1 2; do
    ask_owner_password
    say "      Checking the database as $DB_OWNER (read-only)..."
    run_db_tool check
    [ "$DB_TOOL_RC" = 3 ] || break
    OWNER_PW=""
    say "      The database rejected the user name or password (ORA-01017)."
    [ "$attempt" = 1 ] || finish 1 "the $DB_OWNER login was rejected twice. Check the password with the DBA (more attempts could lock the account)"
  done
  case "$DB_TOOL_RC" in
    0) ;;
    4) OWNER_PW=""; show_db_results; finish 1 "the $DB_OWNER account is locked or its password has expired. Ask the DBA to unlock it or reset the password, then run the installer again" ;;
    5) OWNER_PW=""; show_db_results; finish 1 "the database could not be reached at $DB_HOST:$DB_PORT/$DB_SERVICE (see the error above)" ;;
    1) OWNER_PW=""; show_db_results; finish 1 "the database prerequisites are not complete (the failed checks are listed above). The DBA SQL creates them: run the installer again and choose 1 at the schema step" ;;
    *) OWNER_PW=""; show_db_results; finish 1 "the database check could not be completed (exit $DB_TOOL_RC; see the log)" ;;
  esac
  show_db_results
  case "$DB_STATE" in
    COMPLETE)
      OWNER_PW=""
      say "      The Oracle OPS tables and packages already exist and are valid: nothing to create."
      log "database objects: already complete"
      return 0 ;;
    EMPTY) ;;
    *)
      OWNER_PW=""
      finish 1 "$DB_OWNER holds only part of the Oracle OPS objects. The installer never drops or replaces database objects: ask the DBA to compare the schema with the Oracle OPS release, then run the installer again" ;;
  esac
  say "      $DB_OWNER is empty. The installer will now run, as $DB_OWNER, these scripts of Oracle OPS $OPS_VERSION:"
  local f
  for f in "${DB_RUN_FILES[@]}"; do say "        $f"; done
  if ! confirm_yes "Create the Oracle OPS tables and packages now?"; then
    OWNER_PW=""; finish 5 "no database object was created"
  fi
  say "      Creating the Oracle OPS tables and packages..."
  run_db_tool deploy
  OWNER_PW=""
  show_db_results
  [ "$DB_TOOL_RC" = 0 ] && [ "$DB_STATE" = COMPLETE ] \
    || finish 1 "creating the Oracle OPS database objects failed (the error is shown above; details in the log). Objects already created stay; the installer does not drop them"
  say "      The Oracle OPS tables and packages were created and are valid."
  log "database objects: created"
}
